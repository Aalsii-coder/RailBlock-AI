"""
ai_predictor.py
===============
RailBlock AI — Machine-Learning Risk Predictor

What this module does
─────────────────────
It trains a Random Forest classifier to predict whether a railway asset
(track, signal, overhead equipment, etc.) is likely to FAIL within the
next 30 days.

The predicted risk score is then used downstream to give an AI bonus to
urgency scoring and to help the CP-SAT scheduler prioritise higher-risk
maintenance.

⚠️  IMPORTANT DISCLAIMER ⚠️
─────────────────────────────────────────────────────────────────
The prototype is trained on SYNTHETIC data generated by
synthetic_history.py.

* Synthetic data is NOT real Indian Railways operational data.
* It is NOT sourced from TMS (Train Management System),
  SMMS (Safety Management System), TDMS, or any official database.
* Accuracy figures from this prototype do NOT represent real-world
  Indian Railways failure prediction performance.
* Before production deployment this model MUST be retrained on
  authorised historical data from the relevant Indian Railways
  operational systems.
─────────────────────────────────────────────────────────────────

ML Features used
────────────────
Only physical asset-health indicators are used as features:

    asset_age_years
    days_since_last_maintenance
    recent_defect_count
    failures_last_12_months
    traffic_load_percent

Planning fields (priority, deadline, department, train timings) are
deliberately excluded — they describe scheduling decisions, not asset
condition, and must not contaminate the physical-risk prediction.

Target label
────────────
    failure_within_30_days:  0 = no failure,  1 = failure

Risk levels
───────────
    [0.00, 0.33)  → LOW
    [0.33, 0.66)  → MEDIUM
    [0.66, 1.00]  → HIGH
"""

from sklearn.ensemble import RandomForestClassifier
import copy

# The five features the model is trained on — in a fixed order.
ML_FEATURES = [
    "asset_age_years",
    "days_since_last_maintenance",
    "recent_defect_count",
    "failures_last_12_months",
    "traffic_load_percent",
]

ML_TARGET = "failure_within_30_days"


# ── Risk level helper ─────────────────────────────────────────────────────────

def _score_to_level(score: float) -> str:
    """
    Convert a probability score in [0, 1] to a human-readable risk level.

    Boundaries (exact, inclusive lower, exclusive upper):
        0.00 <= score < 0.33  →  LOW
        0.33 <= score < 0.66  →  MEDIUM
        0.66 <= score <= 1.00 →  HIGH
    """
    if score < 0.33:
        return "LOW"
    elif score < 0.66:
        return "MEDIUM"
    else:
        return "HIGH"


# ── Training ──────────────────────────────────────────────────────────────────

def train_risk_model(historical_records: list) -> dict:
    """
    Train a Random Forest classifier on historical maintenance records.

    Each record must contain the five ML features and the target label
    'failure_within_30_days'.

    Parameters
    ----------
    historical_records : list[dict]
        Training data — typically produced by generate_synthetic_history()
        for prototyping, or from authorised TMS/SMMS/TDMS data in production.

    Returns
    -------
    dict  (model_bundle)
        {
            "model"    : fitted RandomForestClassifier,
            "features" : list of feature names in training order,
            "n_samples": int — number of training records,
            "classes"  : list — class labels [0, 1],
        }

    Raises
    ------
    ValueError  if training data is missing required fields or contains
                fewer than 2 samples.
    """
    if len(historical_records) < 2:
        raise ValueError("Need at least 2 training records.")

    # Build feature matrix X and label vector y
    X = []
    y = []
    for i, rec in enumerate(historical_records):
        row = []
        for feature in ML_FEATURES:
            if feature not in rec:
                raise ValueError(
                    f"Training record [{i}] is missing feature '{feature}'"
                )
            row.append(float(rec[feature]))

        if ML_TARGET not in rec:
            raise ValueError(
                f"Training record [{i}] is missing target '{ML_TARGET}'"
            )
        X.append(row)
        y.append(int(rec[ML_TARGET]))

    # Train the Random Forest.
    # random_state=42 makes results reproducible.
    # n_estimators=100 gives a good balance of accuracy and speed.
    clf = RandomForestClassifier(n_estimators=100, random_state=42)
    clf.fit(X, y)

    return {
        "model": clf,
        "features": list(ML_FEATURES),
        "n_samples": len(historical_records),
        "classes": clf.classes_.tolist(),
    }


# ── Prediction ────────────────────────────────────────────────────────────────

def predict_maintenance_risk(
    data: dict,
    asset_features: list,
    model_bundle: dict,
) -> dict:
    """
    Add AI risk predictions to each maintenance job.

    For every maintenance job in data['maintenance_jobs'], the function
    looks up that job's asset features in asset_features (matched by
    maintenance_id), runs predict_proba() through the trained Random
    Forest, and stores:

        predicted_risk_score  – float in [0, 1], probability of failure
        predicted_risk_level  – "LOW", "MEDIUM", or "HIGH"

    Jobs without a matching asset_features entry receive a neutral
    score of 0.5 and level "MEDIUM" with a flag so downstream modules
    know AI data was unavailable.

    Also adds to the returned dict:
        ai_risk_ranking  – maintenance jobs sorted by risk score, highest first
        ai_model_info    – non-model metadata (no sklearn object) for logging

    Parameters
    ----------
    data : dict
        Validated/standardised railway planning data.
    asset_features : list[dict]
        One dict per maintenance job:
        {
            "maintenance_id": "M001",
            "asset_age_years": ...,
            "days_since_last_maintenance": ...,
            "recent_defect_count": ...,
            "failures_last_12_months": ...,
            "traffic_load_percent": ...,
        }
    model_bundle : dict
        Returned by train_risk_model().

    Returns
    -------
    dict
        Deep copy of data with predictions added to each maintenance job,
        plus 'ai_risk_ranking' and 'ai_model_info' at the top level.
    """
    # Deep copy so we don't mutate the caller's data.
    result = copy.deepcopy(data)

    clf = model_bundle["model"]
    features = model_bundle["features"]

    # Build a lookup: maintenance_id → feature row
    feature_lookup = {}
    for entry in asset_features:
        mid = entry.get("maintenance_id")
        if mid:
            feature_lookup[mid] = entry

    enriched_jobs = []
    for job in result["maintenance_jobs"]:
        mid = job["maintenance_id"]
        job = dict(job)  # shallow copy (all values are scalars / strings)

        if mid in feature_lookup:
            af = feature_lookup[mid]
            # Build the feature row in the same order as training.
            row = [[float(af.get(f, 0.0)) for f in features]]

            # predict_proba returns [[prob_class0, prob_class1]]
            # We want prob_class1 = probability of failure within 30 days.
            proba = clf.predict_proba(row)[0]

            # Find the index for class 1 (failure).
            # classes_ may be [0, 1] or only [0] / [1] if training data
            # happened to contain only one class (edge case).
            if 1 in clf.classes_:
                class1_idx = list(clf.classes_).index(1)
                risk_score = float(proba[class1_idx])
            else:
                # Model only saw class 0 in training — default to 0.
                risk_score = 0.0

            job["predicted_risk_score"] = round(risk_score, 4)
            job["predicted_risk_level"] = _score_to_level(risk_score)
            job["ai_data_available"] = True
        else:
            # No asset feature data for this job — use neutral defaults.
            job["predicted_risk_score"] = 0.5
            job["predicted_risk_level"] = "MEDIUM"
            job["ai_data_available"] = False

        enriched_jobs.append(job)

    result["maintenance_jobs"] = enriched_jobs

    # Build AI risk ranking: highest predicted_risk_score first.
    ai_ranking = sorted(
        enriched_jobs,
        key=lambda j: j["predicted_risk_score"],
        reverse=True,
    )
    result["ai_risk_ranking"] = [
        {
            "maintenance_id": j["maintenance_id"],
            "section": j["section"],
            "predicted_risk_score": j["predicted_risk_score"],
            "predicted_risk_level": j["predicted_risk_level"],
        }
        for j in ai_ranking
    ]

    # Return model metadata without the sklearn object (JSON-safe).
    result["ai_model_info"] = {
        "model_type": "RandomForestClassifier",
        "n_estimators": clf.n_estimators,
        "random_state": clf.random_state,
        "n_training_samples": model_bundle["n_samples"],
        "features_used": features,
        "target_label": ML_TARGET,
        "disclaimer": (
            "Trained on SYNTHETIC data. "
            "NOT real Indian Railways operational data. "
            "Retrain with authorised TMS/SMMS/TDMS data before deployment."
        ),
    }

    return result
