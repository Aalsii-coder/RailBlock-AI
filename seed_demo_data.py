# =========================================================
# SEED
# =========================================================


def seed():
    existing_train_ids = {
        train["train_id"]
        for train in get_all_trains()
    }

    existing_maintenance_ids = {
        job["maintenance_id"]
        for job in get_all_maintenance_requests()
    }

    trains_added = 0
    jobs_added = 0

    for train in TRAINS:
        if train["train_id"] not in existing_train_ids:
            add_train_record(train)
            trains_added += 1

    for job in MAINTENANCE:
        if job["maintenance_id"] not in existing_maintenance_ids:
            add_maintenance_record(job)
            jobs_added += 1

    print()
    print("RailBlock AI demo database seeded.")
    print(f"Trains added: {trains_added}")
    print(f"Maintenance jobs added: {jobs_added}")
    print(f"Total trains: {len(get_all_trains())}")
    print(
        "Total maintenance jobs: "
        f"{len(get_all_maintenance_requests())}"
    )


if __name__ == "__main__":
    seed()